const { webContents } = require("electron");
const wc = webContents.getAllWebContents().find(w => w.getURL().startsWith("t3code://"));
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const ev = (x) => wc.executeJavaScript(x);
const z = wc.getZoomFactor();
const out = [];
const state = () => ev(`(()=>({loaded:[...document.querySelectorAll('[data-list=loaded] .t3m-name')].map(e=>e.textContent), avail:[...document.querySelectorAll('[data-list=available] .t3m-name')].map(e=>e.textContent), foot:document.querySelector('[data-foot]').textContent, apply:(b=>b.hidden?'hidden':b.textContent)(document.querySelector('[data-act=apply]'))}))()`);
await ev(`document.querySelector('button[aria-label="Mods"]').click()`); await sleep(1500);
await ev(`document.querySelector('[data-act=rescan]').click()`); await sleep(1000);
out.push(["initial", await state()]);
await ev(`document.querySelector('.t3m-arrow[data-id=zz-a]').click()`);
await ev(`document.querySelector('.t3m-arrow[data-id=zz-b]').click()`);
await ev(`document.querySelector('.t3m-arrow[data-id=commit-graph]').click()`);
out.push(["staged", await state()]);
const r = await ev(`(()=>{const r=document.querySelector('.t3m-dialog').getBoundingClientRect();return [r.x,r.y,r.width,r.height]})()`);
const img = await wc.capturePage({x:Math.round(r[0]*z),y:Math.round(r[1]*z),width:Math.round(r[2]*z),height:Math.round(r[3]*z)});
require("fs").writeFileSync(ARGS.out+"/st1.png", img.toPNG());
await ev(`document.querySelector('.t3m-arrow[data-id=commit-graph]').click()`);
out.push(["commit-graph restored", await state()]);
await ev(`document.querySelector('[data-act=discard]').click()`);
out.push(["discarded", await state()]);
return JSON.stringify(out,null,1);
