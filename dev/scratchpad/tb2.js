const { BrowserWindow } = require("electron");
const fs = require("fs");
const wc = BrowserWindow.getAllWindows()[0].webContents;
const z = wc.getZoomFactor();
const js = (s) => wc.executeJavaScript(s, true);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
for (let i = 0; i < 20 && !(await js(`!!document.querySelector(".t3cg tr.t3cg-row")`)); i++) await sleep(250);
const panel = await js(`(() => { const c = document.querySelector(".t3cg").getBoundingClientRect(); return { x: c.x, y: c.y, width: c.width, height: 260 }; })()`);
const shot = async (name) => fs.writeFileSync(`${ARGS.out}/${name}.png`, (await wc.capturePage({ x: Math.round(panel.x * z), y: Math.round(panel.y * z), width: Math.round(panel.width * z), height: Math.round(panel.height * z) })).toPNG());
const out = {};
await js(`document.querySelector(".t3cg [data-act=menu]").click(); 0`); await sleep(150);
out.menu = await js(`document.querySelector(".t3cg-menu")?.innerText`);
await shot("menu");
await js(`document.querySelector(".t3cg [data-act=menu]").click(); 0`); await sleep(100);
out.menuClosedByButton = await js(`!document.querySelector(".t3cg-menu")`);
await js(`document.querySelector(".t3cg [data-act=pull]").click(); 0`); await sleep(150);
out.pull = await js(`document.querySelector(".t3cg-overlay")?.innerText`);
await shot("pull");
await js(`document.querySelector(".t3cg-overlay [data-act=cancel]")?.click(); 0`); await sleep(100);
await js(`document.querySelector(".t3cg [data-act=push]").click(); 0`); await sleep(150);
out.push = await js(`document.querySelector(".t3cg-overlay")?.innerText`);
await js(`document.querySelector(".t3cg-overlay [data-act=cancel]")?.click(); 0`); await sleep(100);
out.overlaysLeft = await js(`document.querySelectorAll(".t3cg-overlay,.t3cg-dd").length`);
return out;
